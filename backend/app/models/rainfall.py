"""
backend/app/models/rainfall.py
SQLAlchemy model for point and gridded rainfall observations.
Supports data from multiple sources: station, satellite, radar, NWP.
"""

import uuid

from sqlalchemy import (
    Column, String, Float, Integer, DateTime, CheckConstraint,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.sql import func

from backend.app.core.database import Base


class RainfallData(Base):
    """
    A single rainfall observation or gridded rainfall value.

    UUID is generated by Python (uuid.uuid4) to avoid the SQLAlchemy
    FlushError that occurs when server_default=gen_random_uuid() is used
    without a RETURNING clause on INSERT.
    """

    __tablename__ = "rainfall_data"

    __table_args__ = (
        CheckConstraint(
            "rainfall_mm >= 0",
            name="chk_rainfall_non_negative",
        ),
        CheckConstraint(
            "latitude IS NULL OR (latitude >= -90 AND latitude <= 90)",
            name="chk_rainfall_lat_range",
        ),
        CheckConstraint(
            "longitude IS NULL OR (longitude >= -180 AND longitude <= 180)",
            name="chk_rainfall_lon_range",
        ),
    )

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,             # Python-side: no server_default needed
    )

    observation_time = Column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    source = Column(
        String(50),
        nullable=False,
        index=True,
    )
    # e.g. "STATION", "GPM_IMERG", "RADAR", "NWP", "OPEN_METEO"

    latitude = Column(Float)

    longitude = Column(Float)

    rainfall_mm = Column(
        Float,
        nullable=False,
    )

    duration_minutes = Column(Integer)

    # Optional: station code for station-based observations
    station_code = Column(String(100), index=True)

    # Data quality flag
    quality_flag = Column(
        String(10),
        default="OK",
    )
    # "OK", "SUSPECT", "MISSING", "REJECTED"

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
    )
