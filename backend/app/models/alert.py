"""
backend/app/models/alert.py
SQLAlchemy model for early warning alerts.
Implements full alert lifecycle: created -> active -> updated -> expired/acknowledged.
"""

import uuid

from sqlalchemy import (
    Boolean, Column, String, Float, DateTime, Text, Integer
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.sql import func

from backend.app.core.database import Base


class Alert(Base):
    """
    Early warning alert generated by the risk engine.

    Alert severity levels (ascending):
        INFO -> WATCH -> ADVISORY -> WARNING -> SEVERE_WARNING -> EMERGENCY

    Alert lifecycle:
        CREATED -> ACTIVE -> UPDATED -> EXPIRED | ACKNOWLEDGED
    """

    __tablename__ = "alerts"

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # ---- Timing ----
    alert_time = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        index=True,
    )

    valid_from = Column(DateTime(timezone=True))
    valid_until = Column(DateTime(timezone=True))

    acknowledged_at = Column(DateTime(timezone=True))
    expired_at = Column(DateTime(timezone=True))

    # ---- Classification ----
    alert_type = Column(String(100))            # e.g. "HEAVY_RAIN", "FLASH_FLOOD"
    severity = Column(
        String(50),
        nullable=False,
        index=True,
    )
    # INFO / WATCH / ADVISORY / WARNING / SEVERE_WARNING / EMERGENCY

    status = Column(
        String(30),
        nullable=False,
        default="CREATED",
        index=True,
    )
    # CREATED / ACTIVE / UPDATED / EXPIRED / ACKNOWLEDGED

    # ---- Content ----
    title = Column(String(255), nullable=False)
    message = Column(Text)
    recommended_action = Column(Text)

    # ---- Location ----
    latitude = Column(Float)
    longitude = Column(Float)
    location_name = Column(String(255))
    affected_area_km2 = Column(Float)

    # ---- Trigger values ----
    trigger_rainfall_mm = Column(Float)
    trigger_flood_probability = Column(Float)
    trigger_heavy_rain_probability = Column(Float)
    expected_inundation_area_km2 = Column(Float)
    expected_max_depth_m = Column(Float)

    # ---- Confidence ----
    model_confidence = Column(Float)            # 0-1

    # ---- Traceability ----
    source_prediction_id = Column(
        UUID(as_uuid=True),
    )                                           # FK to flood_predictions
    model_versions = Column(Text)               # JSON

    # ---- Deduplication ----
    is_active = Column(Boolean, default=True, index=True)
    update_count = Column(Integer, default=0)

    created_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
    )

    updated_at = Column(
        DateTime(timezone=True),
        onupdate=func.now(),
    )
