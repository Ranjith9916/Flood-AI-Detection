"""
backend/app/services/rainfall_service.py
Business logic for rainfall data ingestion.
"""
import logging
from datetime import datetime
from typing import Optional

from sqlalchemy.orm import Session

from backend.app.models.rainfall import RainfallData

logger = logging.getLogger(__name__)


def save_rainfall(
    db: Session,
    observation_time: datetime,
    source: str,
    rainfall_mm: float,
    latitude: Optional[float] = None,
    longitude: Optional[float] = None,
    duration_minutes: Optional[int] = None,
    station_code: Optional[str] = None,
    quality_flag: str = "OK",
) -> RainfallData:
    """
    Validate and persist a rainfall observation.
    UUID is generated by Python (uuid.uuid4 in the model default).
    """
    if rainfall_mm < 0:
        raise ValueError(
            f"Rainfall cannot be negative (got {rainfall_mm})"
        )

    if latitude is not None and not (-90 <= latitude <= 90):
        raise ValueError(f"Invalid latitude: {latitude}")

    if longitude is not None and not (-180 <= longitude <= 180):
        raise ValueError(f"Invalid longitude: {longitude}")

    rainfall = RainfallData(
        observation_time=observation_time,
        source=source,
        latitude=latitude,
        longitude=longitude,
        rainfall_mm=rainfall_mm,
        duration_minutes=duration_minutes,
        station_code=station_code,
        quality_flag=quality_flag,
    )

    db.add(rainfall)
    db.commit()
    db.refresh(rainfall)

    logger.debug(
        "Rainfall saved: id=%s source=%s mm=%.2f",
        rainfall.id, source, rainfall_mm,
    )
    return rainfall


def check_duplicate(
    db: Session,
    observation_time: datetime,
    source: str,
    latitude: Optional[float],
    longitude: Optional[float],
) -> bool:
    """Check if an identical record already exists."""
    query = (
        db.query(RainfallData)
        .filter(
            RainfallData.observation_time == observation_time,
            RainfallData.source == source,
        )
    )
    if latitude is not None:
        query = query.filter(RainfallData.latitude == latitude)
    if longitude is not None:
        query = query.filter(RainfallData.longitude == longitude)
    return query.first() is not None
